"""Generate the NCC section of each state and territory page in brain/states/.

Usage:
    python tools/build_state_pages.py

Each brain/states/<code>.md keeps its hand-written notes; this rewrites only
the part between the NCC:START and NCC:END markers, from the NCC pages'
state_variations tables and state-only Parts. Re-run after tools/ncc_ingest.py.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
EDITIONS = ("2025", "2022")
STATES = {"NSW": "New South Wales", "VIC": "Victoria", "QLD": "Queensland", "WA": "Western Australia",
          "SA": "South Australia", "TAS": "Tasmania", "ACT": "Australian Capital Territory", "NT": "Northern Territory"}
def markers(edition: str) -> tuple[str, str]:
    tag = "NCC" if edition == "2025" else f"NCC{edition}"
    return f"<!-- {tag}:START (generated by tools/build_state_pages.py) -->", f"<!-- {tag}:END -->"


def ncc_section(code: str, edition: str = "2025") -> str:
    START, END = markers(edition)
    NCC = ROOT / "brain" / "ncc" / edition
    note = "" if edition == "2025" else " NCC 2022 as published (1 May 2023); read it with Amendments 1 and 2."
    lines = [START, "", f"# NCC {edition} variations", "",
             f"Where {STATES[code]} changes the national code. A variation can replace, add to or delete a clause; the varied text applies in {code}. "
             f"Clause pages show each variation beside the clause.{note}", ""]
    for vol in sorted(NCC.glob("*/state_variations.md")):
        rows = [l for l in vol.read_text().splitlines() if l.startswith(f"| {code} |")]
        title = vol.parent.name.replace("_", " ").title()
        if rows:
            lines += [f"## {title} ({len(rows)})", "", "| State | Variation | Clause or Part |", "|---|---|---|"] + rows + [""]
    own = sorted(p for p in NCC.glob(f"*/{code.lower()}_part_*.md"))
    if own:
        lines += [f"## Parts that apply only in {code}", ""]
        for p in own:
            title = yaml.safe_load(p.read_text().split("---", 2)[1])["title"]
            lines.append(f"- [{title}](/ncc/{edition}/{p.parent.name}/{p.stem}.md)")
        lines.append("")
    return "\n".join(lines + [END])


def main() -> None:
    for code in STATES:
        page = ROOT / "brain" / "states" / f"{code.lower()}.md"
        text = page.read_text()
        counts = []
        for edition in EDITIONS:
            if not (ROOT / "brain" / "ncc" / edition).is_dir():
                continue
            START, END = markers(edition)
            block = ncc_section(code, edition)
            text = re.sub(re.escape(START) + r".*?" + re.escape(END), block, text, flags=re.S) if START in text else text.rstrip() + "\n\n" + block + "\n"
            counts.append(f"NCC {edition}: {block.count(chr(10) + '| ' + code + ' |')}")
        page.write_text(text)
        print(f"{code}: " + ", ".join(counts) + " variations")


if __name__ == "__main__":
    main()
