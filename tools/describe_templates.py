"""Write a Structure section into each document page, describing its template.

Usage:
    python tools/describe_templates.py

For every brain/documents/<name>.md with a `resource:` template, this reads
the template and writes, between the STRUCTURE markers, an outline anyone
can use to produce the same document in another format (their own
letterhead, an email, a PDF):

- Word: the sections in order, each with its labelled fields, table columns
  and prompts.
- Excel: each sheet with its input columns and calculated columns.
- PDF: the brain page it is built from.

Re-run it whenever a template changes.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import openpyxl
import yaml
from docx import Document
from docx.table import Table
from docx.text.paragraph import Paragraph

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).parent))
from docx_tools import PLACEHOLDER  # noqa: E402

START, END = "<!-- STRUCTURE:START (generated by tools/describe_templates.py) -->", "<!-- STRUCTURE:END -->"


def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def is_heading(p: Paragraph) -> bool:
    t = clean(p.text)
    if not t or len(t) > 70 or PLACEHOLDER.fullmatch(t):
        return False
    letters = [c for c in t if c.isalpha()]
    return bool(letters) and sum(c.isupper() for c in letters) / len(letters) > 0.8


def cell_texts(row) -> list[str]:
    out, seen = [], set()
    for c in row.cells:
        if id(c._tc) in seen:
            continue
        seen.add(id(c._tc))
        out.append(clean(c.text))
    return out


def describe_table(t: Table) -> list[str]:
    rows = [cell_texts(r) for r in t.rows]
    rows = [r for r in rows if any(r)]
    if not rows:
        return []
    width = max(len(r) for r in rows)
    lines = []
    if width == 1:
        text = rows[0][0]
        if text.startswith("["):
            lines.append(f"- Free text: {text[:140]}")
        elif text:
            lines.append(f"- Text: {text[:140]}")
        return lines
    header = rows[0]
    looks_like_header = all(h and not PLACEHOLDER.search(h) and not h.endswith(":") and h not in ("$", "☐") for h in header) and len(rows) > 1 \
        and not all(r[0].endswith(":") for r in rows)
    if looks_like_header:
        lines.append(f"- Table with columns: {' | '.join(header)}")
        labels = [r[0] for r in rows[1:] if r and r[0] and not set(r[0]) <= set("_ ")]
        if labels:
            lines.append(f"  - Rows: {', '.join(labels[:30])}" + (" …" if len(labels) > 30 else ""))
        blank = sum(1 for r in rows[1:] if not r[0])
        if blank:
            lines.append(f"  - {blank} blank rows to fill")
        return lines
    for r in rows:
        pairs = []
        for i in range(0, len(r) - 1, 2):
            label, value = r[i], r[i + 1]
            if label and set(label) - set("_ "):
                pairs.append(f"{label} {value}".strip() if value and not set(value) <= set("_ ") else f"{label} (to complete)")
        if not pairs and r[0]:
            pairs.append(" | ".join(x for x in r if x))
        if pairs:
            lines.append("- " + "; ".join(pairs)[:220])
    return lines


def describe_docx(path: Path) -> list[str]:
    doc = Document(path)
    body = doc.element.body
    lines: list[str] = []
    for child in body.iterchildren():
        tag = child.tag.split("}")[-1]
        if tag == "p":
            p = Paragraph(child, doc)
            t = clean(p.text)
            if not t:
                continue
            if is_heading(p):
                lines.append(f"\n**{t.title()}**\n")
            elif t.startswith("☐") or "☐" in t:
                lines.append(f"- Tick boxes: {', '.join(x.strip() for x in t.split('☐') if x.strip())}")
            else:
                lines.append(f"- {t[:220]}")
        elif tag == "tbl":
            lines.extend(describe_table(Table(child, doc)))
    return lines


def describe_xlsx(path: Path) -> list[str]:
    wb = openpyxl.load_workbook(path)
    lines = []
    for ws in wb:
        if ws.title == "Instructions":
            lines.append(f"\n**Sheet: Instructions**: how to use the workbook")
            continue
        lines.append(f"\n**Sheet: {ws.title}**\n")
        if ws.title == "Setup":
            labels = [clean(str(c.value)) for c in ws["A"] if isinstance(c.value, str) and c.value.strip().endswith(":")]
            lines.append(f"- Fields: {', '.join(l.rstrip(':') for l in labels)}")
            continue
        header_row = None
        for row in ws.iter_rows(min_row=1, max_row=8):
            vals = [c.value for c in row if c.value not in (None, "")]
            if len(vals) >= 3 and all(isinstance(v, str) and not v.startswith("=") for v in vals):
                header_row = row[0].row
        if header_row:
            inputs, calcs = [], []
            for c in ws[header_row]:
                if not isinstance(c.value, str) or not c.value.strip():
                    continue
                below = ws.cell(row=header_row + 1, column=c.column).value
                (calcs if isinstance(below, str) and below.startswith("=") else inputs).append(clean(c.value))
            lines.append(f"- One row per entry from row {header_row + 1}. Columns to enter: {', '.join(inputs)}")
            if calcs:
                lines.append(f"- Calculated columns: {', '.join(calcs)}")
            fixed = [clean(str(ws.cell(row=r, column=1).value)) for r in range(header_row + 1, ws.max_row + 1)
                     if isinstance(ws.cell(row=r, column=1).value, str) and not str(ws.cell(row=r, column=1).value).startswith("=")]
            if fixed:
                lines.append(f"- Pre-set rows: {', '.join(fixed[:25])}" + (" …" if len(fixed) > 25 else ""))
        else:
            labels = [clean(str(c.value)) for c in ws["A"] if isinstance(c.value, str) and not c.value.startswith("=")]
            lines.append(f"- Lines: {', '.join(labels[:30])}")
        dv = [f"{d.sqref}: {d.formula1.strip(chr(34))}" for d in ws.data_validations.dataValidation if d.formula1]
        if dv:
            lines.append(f"- Dropdown values: {'; '.join(dv)}")
    return lines


def describe(meta: dict) -> list[str]:
    path = ROOT / meta["resource"]
    if path.suffix == ".docx":
        out = describe_docx(path)
        ph = sorted(set(m for line in out for m in PLACEHOLDER.findall(line)) - {"[LOGO]"})
        return out + ["", f"Fields from the project file: {', '.join(f'`{p}`' for p in ph)} (see [project fields](/fields/project_fields.md))."]
    if path.suffix == ".xlsx":
        return describe_xlsx(path)
    for page in (ROOT / "brain").rglob("*.md"):
        text = page.read_text()
        if f"pdf: {meta['resource']}" in text:
            rel = "/" + page.relative_to(ROOT / "brain").as_posix()
            return [f"Built from the brain page [{yaml.safe_load(text.split('---', 2)[1])['title']}]({rel}) by `tools/build_pdfs.py`. "
                    "Use that page as the reference: it holds the full content, and editing it and rebuilding updates the PDF."]
    return ["A PDF reference document."]


def main() -> None:
    n = 0
    for page in sorted((ROOT / "brain" / "documents").glob("*.md")):
        if page.name == "index.md":
            continue
        text = page.read_text()
        meta = yaml.safe_load(text.split("---", 2)[1])
        if not meta.get("resource"):
            continue
        block = "\n".join([START, "", "# Structure", "",
                           "Use this outline to produce the document in any format (your own letterhead, an email, a PDF). "
                           "To fill the template itself, use `tools/fill_template.py`.", ""]
                          + describe(meta) + ["", END])
        block = re.sub(r"\n{3,}", "\n\n", block)
        if START in text:
            text = re.sub(re.escape(START) + r".*?" + re.escape(END), block, text, flags=re.S)
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
        page.write_text(text)
        n += 1
    print(f"{n} document pages described")


if __name__ == "__main__":
    main()
